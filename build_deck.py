def source(s, src):
    txt(s, Inches(0.55), Inches(7.06), Inches(11.4), Inches(0.32),
        [[("Source: ", 7.5, GREY, True), (src, 7.5, GREY, False)]], anchor=MSO_ANCHOR.MIDDLE, ls=0.95)

def title(s, t, kicker=None):
    if kicker:
        txt(s, Inches(0.57), Inches(0.34), Inches(9.5), Inches(0.3), Pn(kicker.upper(), 10.5, GREEN_D, True), sa=0)
        txt(s, Inches(0.55), Inches(0.6), Inches(10.2), Inches(0.7), Pn(t, 27, NAVY, True), sa=0)
    else:
        txt(s, Inches(0.55), Inches(0.42), Inches(10.2), Inches(0.8), Pn(t, 30, NAVY, True), sa=0)
    rect(s, Inches(0.57), Inches(1.32), Inches(2.2), Pt(3), ORANGE)

def base(s, t, n, src, kicker=None):
    rect(s, 0, 0, EMU_W, EMU_H, WHITE)
    title(s, t, kicker); running_header(s); pagenum(s, n)
    if src: source(s, src)

def stat_card(s, x, y, w, h, val, lab, accent=ORANGE):
    rect(s, x, y, w, h, PANEL, line=LINE, lw=Pt(0.75)); rect(s, x, y, Pt(4), h, accent)
    txt(s, x+Inches(0.2), y+Inches(0.13), w-Inches(0.32), Inches(0.5), Pn(val, 20, NAVY, True), sa=0)
    txt(s, x+Inches(0.2), y+h-Inches(0.5), w-Inches(0.32), Inches(0.46), Pn(lab, 9, GREY, False), sa=0, ls=0.95)

def col_chart(s, x, y, w, h, cats, vals, accent=BLUE, numfmt='#,##0.00', lblsz=9):
    cd = CategoryChartData(); cd.categories = cats; cd.add_series("s", vals)
    ch = s.shapes.add_chart(XL_CHART_TYPE.COLUMN_CLUSTERED, x, y, w, h, cd).chart
    ch.has_legend=False; ch.has_title=False; ch.font.name=F
    pl = ch.plots[0]; pl.gap_width=55; pl.has_data_labels=True
    dl=pl.data_labels; dl.number_format=numfmt; dl.number_format_is_linked=False
    dl.font.size=Pt(lblsz); dl.font.bold=True; dl.font.color.rgb=NAVY; dl.font.name=F
    dl.position=XL_LABEL_POSITION.OUTSIDE_END
    pl.series[0].format.fill.solid(); pl.series[0].format.fill.fore_color.rgb=accent
    ca=ch.category_axis; ca.tick_labels.font.size=Pt(9); ca.tick_labels.font.name=F
    ca.tick_labels.font.color.rgb=GREY; ca.format.line.color.rgb=LINE
    va=ch.value_axis; va.visible=False; va.has_major_gridlines=False
    return ch

def bar_chart(s, x, y, w, h, cats, vals, accent=BLUE, numfmt='0.0"%"'):
    cd = CategoryChartData(); cd.categories = cats; cd.add_series("s", vals)
    ch = s.shapes.add_chart(XL_CHART_TYPE.BAR_CLUSTERED, x, y, w, h, cd).chart
    ch.has_legend=False; ch.has_title=False; ch.font.name=F
    pl = ch.plots[0]; pl.gap_width=50; pl.has_data_labels=True
    dl=pl.data_labels; dl.number_format=numfmt; dl.number_format_is_linked=False
    dl.font.size=Pt(10); dl.font.bold=True; dl.font.color.rgb=NAVY; dl.font.name=F
    dl.position=XL_LABEL_POSITION.OUTSIDE_END
    pl.series[0].format.fill.solid(); pl.series[0].format.fill.fore_color.rgb=accent
    ca=ch.category_axis; ca.tick_labels.font.size=Pt(10); ca.tick_labels.font.name=F
    ca.tick_labels.font.color.rgb=GREY; ca.format.line.color.rgb=LINE
    va=ch.value_axis; va.visible=False; va.has_major_gridlines=False
    return ch

